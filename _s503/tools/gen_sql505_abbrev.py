"""S505 — gen_sql505_abbrev.py → data-schema/migrations/session505_abbrev_book_names.sql — the MECHANICAL fix for 2 Baruch's and Testaments XII's
cards whose note (and member note) opens with an abbreviated book name (`Prov 6:23 —`, `1 Jn 3:12 —`): the abbreviation is expanded to the
conventional English book name the voice skill requires (`Proverbs 6:23 —`). Nothing else in the note changes — no redraft. Each card's
abbreviation is checked against the card's own TARGET book before it is rewritten; a mismatch is a FAIL and nothing is generated.
Guards (DO block): card gone / off its verse pair / source text moved / note neither old nor new / member row neither old nor new → RAISE, nothing
lands. Idempotent. Nothing deleted. Model: Claude Fable 5.1 (claude-fable-5-1)."""
import json, re, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from common503 import *
ABBR = {'Matt': ('Matthew', 'matthew'), 'Mk': ('Mark', 'mark'), 'Lk': ('Luke', 'luke'), 'Jn': ('John', 'john'), 'Gen': ('Genesis', 'genesis'),
        'Exod': ('Exodus', 'exodus'), 'Exo': ('Exodus', 'exodus'), 'Lev': ('Leviticus', 'leviticus'), 'Num': ('Numbers', 'numbers'),
        'Deut': ('Deuteronomy', 'deuteronomy'), 'Isa': ('Isaiah', 'isaiah'), 'Jer': ('Jeremiah', 'jeremiah'), 'Ezek': ('Ezekiel', 'ezekiel'),
        'Dan': ('Daniel', 'daniel'), 'Hos': ('Hosea', 'hosea'), 'Zech': ('Zechariah', 'zechariah'), 'Mal': ('Malachi', 'malachi'),
        'Ps': ('Psalm', 'psalms'), 'Prov': ('Proverbs', 'proverbs'), 'Rom': ('Romans', 'romans'), 'Gal': ('Galatians', 'galatians'),
        'Heb': ('Hebrews', 'hebrews'), 'Rev': ('Revelation', 'revelation')}
LEAD = re.compile(r"^(?P<num>[123] )?(?P<ab>Matt|Mk|Lk|Jn|Gen|Exod?|Lev|Num|Deut|Isa|Jer|Ezek|Dan|Hos|Zech|Mal|Ps|Prov|Rom|Gal|Heb|Rev)\.? (?P<c>\d+):(?P<v>\d+)")
def expand(text, c):
    m = LEAD.match(text or '')
    if not m: return None
    full, slug = ABBR[m.group('ab')]; num = m.group('num') or ''
    slug = f"{num.strip()}-{slug}" if num else slug
    if slug != c['t_book'] or int(m.group('c')) != c['t_ch'] or int(m.group('v')) != c['t_vn']:
        raise SystemExit(f"card {c['id']}: lead '{m.group(0)}' does not name its target {c['t_book']} {c['t_ch']}:{c['t_vn']}")
    return f"{num}{full} {m.group('c')}:{m.group('v')}" + text[m.end():]
def q(s, tag='n'):
    assert f'${tag}$' not in s; return f'${tag}$' + s + f'${tag}$'
rows = []; per = {}
for ed, bk in (('pseudepigrapha', '2-baruch'), ('pseudepigrapha', 'testaments-xii')):
    D = load503(ed, bk); M = {m['xref_id']: m for m in D['members']}; n = 0
    for c in D['cards']:
        if c['s_book'] != bk or c['s_ed'] != ed: continue
        new = expand(c['note'], c)
        if new is None: continue
        m = M.get(c['id'])
        if m is None: raise SystemExit(f"card {c['id']} has an abbreviated note but no member row")
        newm = expand(m['member_note'], c)
        if newm is None: raise SystemExit(f"card {c['id']}: member note does not open with the abbreviation its note does")
        rows.append(dict(id=c['id'], s_ed=ed, s_book=bk, src_ch=c['s_ch'], src_vn=c['s_vn'], src_text=c['s_text'], t_ed=c['t_ed'], tgt_book=c['t_book'], tgt_ch=c['t_ch'], tgt_vn=c['t_vn'],
                         old_note=c['note'], new_note=new, thread_id=m['thread_id'], old_mnote=m['member_note'], new_mnote=newm)); n += 1
    per[bk] = (n, D['schema_note'])
vals = ',\n'.join(f"({r['id']}, '{r['s_ed']}', '{r['s_book']}', {r['src_ch']}, {r['src_vn']}, {q(r['src_text'])}, '{r['t_ed']}', '{r['tgt_book']}', {r['tgt_ch']}, {r['tgt_vn']}, {q(r['old_note'])}, {q(r['new_note'])}, {r['thread_id']}, {q(r['old_mnote'])}, {q(r['new_mnote'])})" for r in rows)
sql = f"""-- =====================================================================
-- Session 505 migration — abbreviated book names EXPANDED in {len(rows)} card notes and their member notes:
-- 2 Baruch {per['2-baruch'][0]} ({per['2-baruch'][1]}), Testaments XII {per['testaments-xii'][0]} ({per['testaments-xii'][1]}).
-- Mechanical: only the opening citation changes (`Prov 6:23 —` → `Proverbs 6:23 —`, `1 Jn 3:12` → `1 John 3:12`); the prose is untouched.
-- Guards RAISE before any write if a card is gone, off its verse pair, its source text moved, or its note / member note is neither the old
-- nor the new text. Idempotent (re-run: 0 rewritten). Nothing deleted. Generated by _s503/tools/gen_sql505_abbrev.py on Claude Fable 5.1.
-- Run: python3 api/apply_migration.py data-schema/migrations/session505_abbrev_book_names.sql
-- =====================================================================
\\echo 'session505 — abbreviated book names starting...'
BEGIN;
CREATE TEMP TABLE s505_cards (id bigint, s_ed text, s_book text, src_ch int, src_vn int, src_text text, t_ed text, tgt_book text, tgt_ch int, tgt_vn int, old_note text, new_note text, thread_id bigint, old_mnote text, new_mnote text) ON COMMIT DROP;
INSERT INTO s505_cards VALUES
{vals};
DO $s505$
DECLARE r record; x record; n int;
BEGIN
  FOR r IN SELECT * FROM s505_cards LOOP
    SELECT xr.id, xr.note, sv.text AS stext, se.slug AS sed, sb.slug AS sbook, sc.chapter_number AS sch, sv.verse_number AS svn, te.slug AS ted, tb.slug AS tbook, tc.chapter_number AS tch, tv.verse_number AS tvn
      INTO x FROM cross_references xr
      JOIN verses sv ON sv.id = xr.source_verse_id JOIN chapters sc ON sc.id = sv.chapter_id JOIN books sb ON sb.id = sc.book_id JOIN editions se ON se.id = sb.edition_id
      JOIN verses tv ON tv.id = xr.target_verse_id JOIN chapters tc ON tc.id = tv.chapter_id JOIN books tb ON tb.id = tc.book_id JOIN editions te ON te.id = tb.edition_id
      WHERE xr.id = r.id;
    IF NOT FOUND THEN RAISE EXCEPTION 'S505: card % is gone', r.id; END IF;
    IF x.sed <> r.s_ed OR x.sbook <> r.s_book OR x.sch <> r.src_ch OR x.svn <> r.src_vn OR x.ted <> r.t_ed OR x.tbook <> r.tgt_book OR x.tch <> r.tgt_ch OR x.tvn <> r.tgt_vn THEN
      RAISE EXCEPTION 'S505: card % no longer sits on the verse pair this was written for', r.id; END IF;
    IF x.stext <> r.src_text THEN RAISE EXCEPTION 'S505: live text of % %:% differs from the read-back — re-dump and rebuild', r.s_book, r.src_ch, r.src_vn; END IF;
    IF x.note IS DISTINCT FROM r.old_note AND x.note IS DISTINCT FROM r.new_note THEN RAISE EXCEPTION 'S505: the live note of card % differs from the read-back — re-dump and rebuild', r.id; END IF;
    SELECT count(*) INTO n FROM cross_reference_thread_members m WHERE m.cross_reference_id = r.id AND m.thread_id = r.thread_id AND (m.member_note IS NOT DISTINCT FROM r.old_mnote OR m.member_note IS NOT DISTINCT FROM r.new_mnote);
    IF n <> 1 THEN RAISE EXCEPTION 'S505: card % has no member row in thread % carrying the member note this was written against', r.id, r.thread_id; END IF;
  END LOOP;
END $s505$;
DO $s505b$
DECLARE n_notes int; n_m int; n_c int;
BEGIN
  SELECT count(*) INTO n_c FROM s505_cards;
  UPDATE cross_references xr SET note = c.new_note FROM s505_cards c WHERE xr.id = c.id AND xr.note IS NOT DISTINCT FROM c.old_note AND c.old_note IS DISTINCT FROM c.new_note;
  GET DIAGNOSTICS n_notes = ROW_COUNT;
  UPDATE cross_reference_thread_members m SET member_note = c.new_mnote FROM s505_cards c WHERE m.cross_reference_id = c.id AND m.thread_id = c.thread_id AND m.member_note IS NOT DISTINCT FROM c.old_mnote AND c.old_mnote IS DISTINCT FROM c.new_mnote;
  GET DIAGNOSTICS n_m = ROW_COUNT;
  RAISE NOTICE 'S505 abbreviations: notes rewritten % / already there %; member notes rewritten % / already there %', n_notes, n_c - n_notes, n_m, n_c - n_m;
END $s505b$;
COMMIT;
\\echo 'session505 — abbreviated book names done.'
"""
out = W3.parent / 'data-schema' / 'migrations' / 'session505_abbrev_book_names.sql'; out.write_text(sql)
json.dump(rows, open(W3 / 'fix' / 'abbrev505.json', 'w'), ensure_ascii=False, indent=1)
print(f"{len(rows)} cards ({per}) -> {out}")
